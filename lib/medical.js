export async function askMedical(question) {
  return callClaude(MEDICAL_SYSTEM, question);
}

export async function askProtocol(query) {
  return callClaude(PROTOCOL_SYSTEM, query);
}

export async function askClinicalCase(topic) {
  return callClaude(CASES_SYSTEM, `Створи клінічний випадок на тему: ${topic}`);
}

export async function askMedicalNews(topic) {
  const query = topic
    ? `Останні новини та дослідження з теми: ${topic}`
    : "Останні важливі новини та дослідження в медицині";
  return callClaude(NEWS_SYSTEM, query);
}

async function callClaude(system, question) {
  try {
    const response = await anthropic.messages.create({
      model: "claude-sonnet-4-20250514",
      max_tokens: 4096,
      system,
      messages: [{ role: "user", content: question }],
    });
    return response.content[0].text;
  } catch (err) {
    console.error("Medical AI error:", err);
    if (err.message?.includes("credit balance")) {
      return "⚠️ Недостатньо кредитів Claude API. Поповни на console.anthropic.com";
    }
    return "⚠️ Помилка AI. Спробуй ще раз.";
  }
}
